"""Generate and bind a fixed, exploratory family-disjoint synthetic dataset."""
from __future__ import annotations

import argparse
from collections import Counter
from hashlib import sha256
from importlib.metadata import version
import json
import math
import os
from pathlib import Path
import stat

from ml.synthetic.dataset import FAMILY_AXES, PRESETS, _build_scenes, _split_manifests, generate_dataset
from ml.synthetic.io import canonical_json_bytes

ROOT = Path(__file__).resolve().parents[3]
SEED = 20261030
SCHEMA = "graphreader.synthetic-tick-family-dataset.v1"


def digest(path: Path) -> str:
    return sha256(path.read_bytes()).hexdigest()


def _fixed_scenes() -> list[dict]:
    return _build_scenes(PRESETS["real_range"], SEED, require_complete_style_catalog=False)


def _disk_files(root: Path) -> set[str]:
    result = set()
    for base, directories, files in os.walk(root, followlinks=False):
        for name in directories + files:
            path = Path(base) / name
            info = path.lstat()
            if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400):
                raise ValueError("dataset contains a link or reparse point")
        for name in files:
            result.add((Path(base) / name).relative_to(root).as_posix())
    return result


def _validate_x_tick(item: dict, panel: dict, scene: dict, width: int, height: int) -> None:
    text, box, position = item.get("text"), item.get("rendered_pixel_box"), item.get("position")
    if (not isinstance(text, str) or not text.isascii() or not text.isdecimal() or
            not isinstance(box, list) or len(box) != 4 or
            not isinstance(position, list) or len(position) != 2 or
            any(type(v) not in (int, float) or not math.isfinite(v) for v in box + position)):
        raise ValueError("invalid X-tick text or geometry")
    x, y, w, h = box
    if w <= 0 or h <= 0 or x < 0 or y < 0 or x + w > width or y + h > height:
        raise ValueError("X-tick box outside source canvas")
    if item.get("coordinate_space") != "original_pixels" or item.get("panel_id") != panel.get("panel_id"):
        raise ValueError("X-tick coordinate or panel mismatch")
    matches = [tick for tick in panel["ticks"] if tick.get("axis") == "x" and
               tick.get("panel_id") == panel["panel_id"] and tick.get("visible") is True and
               type(tick.get("value")) in (int, float) and math.isfinite(tick["value"]) and
               tick["value"] == int(text) and isinstance(tick.get("center"), list) and
               len(tick["center"]) == 2 and all(type(v) in (int, float) and math.isfinite(v) for v in tick["center"]) and
               abs(position[0] + 10.0 - tick["center"][0]) < 0.01 and
               abs(position[1] - (tick["center"][1] + 6.0)) < 0.01]
    if len(matches) != 1:
        raise ValueError("X-tick label does not bind one visible tick")
    source_text = [value for value in scene["annotations"]["text_regions"]
                   if value.get("region_id") == item.get("region_id")]
    source_panels = [value for value in scene["panels"] if value.get("panel_id") == panel["panel_id"]]
    if (len(source_text) != 1 or len(source_panels) != 1 or
            source_text[0].get("role") != "x_tick" or source_text[0].get("visible") is not True or
            source_text[0].get("text") != text or source_text[0].get("panel_id") != panel["panel_id"] or
            source_text[0].get("box", [])[:2] != position):
        raise ValueError("X-tick text differs from fixed source scene")
    original_ticks = [tick for tick in source_panels[0]["ticks"]
                      if tick.get("tick_id") == matches[0].get("tick_id")]
    if (len(original_ticks) != 1 or original_ticks[0].get("hidden") is not False or
            original_ticks[0].get("axis") != "x" or original_ticks[0].get("value") != int(text) or
            original_ticks[0].get("center") != matches[0]["center"]):
        raise ValueError("X-tick geometry differs from fixed source scene")


def summarize(dataset: Path) -> dict:
    """Check generated bytes and summarize families, text and candidate artifacts."""
    dataset = dataset.resolve()
    manifest_path = dataset / "seed-manifest.json"
    manifest = json.loads(manifest_path.read_bytes())
    if manifest.get("preset") != "real_range" or manifest.get("dataset_seed") != SEED or not manifest.get("sanity_passed"):
        raise ValueError("unexpected generated dataset identity")
    expected_scenes = _fixed_scenes()
    if len(expected_scenes) != 10 or len(manifest.get("cases", [])) != 10:
        raise ValueError("fixed preset must contain exactly ten cases")
    expected_artifacts = {"contact-sheet.png", "distribution-report.json", "sanity-report.json",
                          "splits/train.json", "splits/validation.json", "splits/test.json"}
    for case in manifest["cases"]:
        scene_id = case["scene_id"]
        expected_case_files = {f"{name}/{scene_id}.{extension}" for name, extension in
                               (("images", "png"), ("scenes", "json"), ("annotations", "json"),
                                ("masks", "png"), ("tables", "csv"))}
        if set(case["files"]) != expected_case_files:
            raise ValueError("case artifact inventory mismatch")
        expected_artifacts.update(case["files"])
    artifacts = manifest.get("artifact_sha256")
    if not isinstance(artifacts, dict) or set(artifacts) != expected_artifacts:
        raise ValueError("seed manifest artifact inventory mismatch")
    if _disk_files(dataset) != expected_artifacts | {"seed-manifest.json"}:
        raise ValueError("dataset disk inventory mismatch")
    for relative, expected_hash in artifacts.items():
        path = (dataset / relative).resolve()
        if not path.is_relative_to(dataset) or not path.is_file() or digest(path) != expected_hash:
            raise ValueError("seed manifest artifact identity mismatch")
    if any(artifacts.get(path) != value for case in manifest["cases"] for path, value in case["files"].items()):
        raise ValueError("case and seed manifest hashes disagree")
    expected_splits = _split_manifests(manifest["cases"])
    for split, expected in expected_splits.items():
        actual = json.loads((dataset / "splits" / f"{split}.json").read_bytes())
        if actual != expected:
            raise ValueError("split manifest differs from fixed cases")
    groups = {split: {"cases": [], "families": {axis: set() for axis in FAMILY_AXES},
                      "fonts": set(), "images": set(), "text_roles": Counter(),
                      "marker_artifact_candidates": Counter()} for split in ("train", "validation")}
    seen_scene_ids: set[str] = set()
    seen_text_ids: set[str] = set()
    for index, case in enumerate(manifest["cases"]):
        split, scene_id = case["split"], case["scene_id"]
        if split not in groups or scene_id in seen_scene_ids:
            raise ValueError("unexpected split or duplicate scene")
        seen_scene_ids.add(scene_id)
        image_rel, ann_rel = f"images/{scene_id}.png", f"annotations/{scene_id}.json"
        scene_rel = f"scenes/{scene_id}.json"
        for relative in (image_rel, ann_rel, scene_rel):
            if relative not in case["files"] or digest(dataset / relative) != case["files"][relative]:
                raise ValueError("dataset file identity mismatch")
        annotation = json.loads((dataset / ann_rel).read_bytes())
        scene = json.loads((dataset / scene_rel).read_bytes())
        if (case.get("case_index") != index or scene != expected_scenes[index] or
                case.get("seed") != scene.get("seed") or case.get("design") != scene.get("design")):
            raise ValueError("scene differs from exact fixed preset")
        if annotation.get("scene_id") != scene_id or annotation.get("coordinate_space") != "original_pixels":
            raise ValueError("annotation identity mismatch")
        if scene.get("scene_id") != scene_id or any(
                scene["families"][axis] != {"key": case["families"][axis], "split": split}
                for axis in FAMILY_AXES):
            raise ValueError("scene family identity mismatch")
        group = groups[split]
        for axis in FAMILY_AXES:
            group["families"][axis].add(case["families"][axis])
        font = annotation["font"]
        font_path = Path(font["resolved_path"])
        if not font_path.is_file() or digest(font_path) != font["sha256"]:
            raise ValueError("rendering font changed")
        group["fonts"].add(font["sha256"])
        image_sha = case["files"][image_rel]
        if image_sha in group["images"]:
            raise ValueError("duplicate image")
        group["images"].add(image_sha)
        visible_x = 0
        observed_x_ids: set[str] = set()
        width, height = annotation["canvas"]["width"], annotation["canvas"]["height"]
        if type(width) is not int or type(height) is not int or width <= 0 or height <= 0:
            raise ValueError("invalid source canvas")
        for panel in annotation["panels"]:
            for item in panel["texts"]:
                if not item.get("visible", True):
                    continue
                box = item.get("rendered_pixel_box")
                if not isinstance(box, list) or len(box) != 4 or box[2] <= 0 or box[3] <= 0:
                    raise ValueError("visible text lacks a rendered box")
                text_id = item.get("text_id")
                if not isinstance(text_id, str) or not text_id or text_id in seen_text_ids:
                    raise ValueError("duplicate or missing text identity")
                seen_text_ids.add(text_id)
                if item["role"] == "x_tick":
                    _validate_x_tick(item, panel, scene, width, height)
                    if item["region_id"] in observed_x_ids:
                        raise ValueError("duplicate X-tick region identity")
                    observed_x_ids.add(item["region_id"])
                group["text_roles"][item["role"]] += 1
                visible_x += item["role"] == "x_tick"
        expected_x_ids = {item["region_id"] for item in scene["annotations"]["text_regions"]
                          if item.get("role") == "x_tick" and item.get("visible") is True}
        if observed_x_ids != expected_x_ids:
            raise ValueError("X-tick truth coverage differs from fixed source scene")
        for item in annotation["hard_negatives"]:
            group["marker_artifact_candidates"][item["kind"]] += 1
        group["cases"].append({"scene_id": scene_id, "seed": case["seed"], "families": case["families"],
                               "image": {"path": image_rel, "sha256": image_sha},
                               "annotation": {"path": ann_rel, "sha256": case["files"][ann_rel]},
                               "scene": {"path": scene_rel, "sha256": case["files"][scene_rel]},
                               "visible_x_tick_count": visible_x, "font_sha256": font["sha256"]})
    train, dev = groups["train"], groups["validation"]
    if not train["cases"] or not dev["cases"]:
        raise ValueError("both splits must be nonempty")
    if len(train["cases"]) != 4 or len(dev["cases"]) != 6:
        raise ValueError("fixed preset must contain four train and six validation cases")
    for axis in FAMILY_AXES:
        if train["families"][axis] & dev["families"][axis]:
            raise ValueError(f"overlapping {axis} families")
    if train["images"] & dev["images"] or train["fonts"] & dev["fonts"]:
        raise ValueError("overlapping image or font bytes")
    if any(group["text_roles"]["x_tick"] == 0 for group in groups.values()):
        raise ValueError("each split must contain visible X-tick labels")
    splits = {}
    for name, group in groups.items():
        splits[name] = {"scene_count": len(group["cases"]), "cases": group["cases"],
                        "families": {axis: sorted(group["families"][axis]) for axis in FAMILY_AXES},
                        "font_sha256": sorted(group["fonts"]), "visible_text_roles": dict(sorted(group["text_roles"].items())),
                        "marker_artifact_candidates": dict(sorted(group["marker_artifact_candidates"].items()))}
    sources = sorted((ROOT / "ml/synthetic").glob("*.py")) + [Path(__file__).resolve()]
    source_hashes = {path.relative_to(ROOT).as_posix(): digest(path) for path in sources}
    return {"schema": SCHEMA, "seed": SEED, "generator": "ml.synthetic.dataset:real_range",
            "generator_source_sha256": source_hashes,
            "seed_manifest_sha256": digest(manifest_path), "pillow_version": version("Pillow"),
            "family_axes_disjoint": list(FAMILY_AXES), "font_bytes_disjoint": True,
            "image_bytes_disjoint": True, "synthetic_only": True, "private_reads": 0,
            "sealed_reads": 0, "optimizer_steps": 0, "production_approved": False,
            "hard_negative_scope": "marker-artifact candidate regions only; not verified OCR-negative labels",
            "limitations": ["No source-family independence from historical benchmarks is asserted.",
                            "Fonts and renderer versions are host-dependent; hashes identify this rendering.",
                            "This exploratory dataset does not authorize model training or acceptance."],
            "splits": splits}


def prepare(output: Path) -> dict:
    output = output.resolve()
    if not output.is_relative_to((ROOT / "artifacts").resolve()) or output.exists():
        raise ValueError("output must be a new project-local artifacts directory")
    output.mkdir(parents=True, exist_ok=False)
    dataset = output / "dataset"
    generate_dataset("real_range", SEED, dataset)
    summary = summarize(dataset)
    with (output / "manifest.json").open("xb") as stream:
        stream.write(canonical_json_bytes(summary))
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = prepare(args.output)
    print(json.dumps({name: {"scenes": value["scene_count"], "x_tick": value["visible_text_roles"]["x_tick"]}
                      for name, value in result["splits"].items()}, sort_keys=True))


if __name__ == "__main__":
    main()
